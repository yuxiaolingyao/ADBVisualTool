import { chromium } from 'playwright-core'
const browser = await chromium.connectOverCDP('http://127.0.0.1:9224')
const page = browser.contexts().flatMap((context) => context.pages())[0]
await page.getByText('ADB 工具箱').first().waitFor({ timeout: 15000 })
await page.evaluate(() => window.api.selectDevice('3B1F66E9ZUZ661VN'))
await page.waitForTimeout(800)
await page.locator('.ant-menu-item').filter({ hasText: '测试工具' }).first().click()
await page.getByText('测试工具', { exact: true }).first().waitFor({ timeout: 10000 })
const left = await page.locator('.tool-left').boundingBox()
const right = await page.locator('.tool-result-col').boundingBox()
console.log('LEFT=' + JSON.stringify(left) + ' RIGHT=' + JSON.stringify(right))
if (!left || !right || right.x <= left.x) throw new Error('结果区不在右侧')
await page.locator('button').filter({ hasText: '当前界面' }).first().click()
await page.waitForTimeout(1500)
const result = await page.locator('.tool-result-col .command-output').innerText()
console.log('RESULT=' + result.replace(/\s+/g, ' ').slice(0, 300))
if (!result.trim()) throw new Error('右侧没有结果')
await page.screenshot({ path: 'tests/e2e/live-layout.png', fullPage: true })

await page.locator('.ant-menu-item').filter({ hasText: '终端' }).first().click()
await page.getByText('终端', { exact: true }).first().waitFor({ timeout: 10000 })
await page.locator('.ant-select').filter({ hasText: '模板' }).first().click()
await page.getByText('设备型号', { exact: true }).first().click()
await page.waitForTimeout(500)
const inputValue = await page.getByPlaceholder(/输入 adb shell 命令/).inputValue()
const entries = await page.locator('.terminal-entry').count()
console.log('TEMPLATE_INPUT=' + inputValue + ' ENTRIES=' + entries)
if (inputValue !== 'getprop ro.product.model') throw new Error('模板没有正确填入')
if (entries !== 0) throw new Error('模板被自动执行了')
await page.screenshot({ path: 'tests/e2e/live-terminal-template.png', fullPage: true })
console.log('LAYOUT TERMINAL E2E OK')
process.exit(0)
